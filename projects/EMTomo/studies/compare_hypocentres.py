"""Compare matched soft/hard inversions of an independently saved experiment.

From the EMTomo root, after generating and solving the forward experiment:
    python studies/compare_hypocentres.py EXPERIMENT_ID --workers 1
Or analyze a completed pair without running the solver:
    python studies/compare_hypocentres.py EXPERIMENT_ID --soft-run runs/RUN_SOFT --hard-run runs/RUN_HARD

For the recorded example, see studies/README.md and create the forward inputs
separately from the repository root:
    python -m projects.forward_modeling.hypocentre_ambiguity_example
    python -m projects.forward_modeling ambiguity24x18x12_8st_80ev_seed17 --refinement 12 --check-convergence --noise --noise-relative-sigma 0 --noise-absolute-sigma-s 0.12 --noise-seed 17
No forward inputs, arrivals, or event truth are generated by this script.
"""
